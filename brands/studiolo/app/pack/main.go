// Build-time packer: turns the web app folder into one encrypted blob (app.bin) and
// writes the matching key into keydata.go, so the shipped .exe contains no readable
// HTML, CSS or JavaScript. Run by tools/build_exe.py; not part of the shipped app.
package main

import (
	"archive/zip"
	"bytes"
	"crypto/aes"
	"crypto/cipher"
	"crypto/rand"
	"fmt"
	"io/fs"
	"os"
	"path/filepath"
	"strings"
)

func main() {
	if len(os.Args) != 4 {
		fmt.Fprintln(os.Stderr, "usage: pack <resources dir> <out app.bin> <out keydata.go>")
		os.Exit(2)
	}
	src, outBin, outKey := os.Args[1], os.Args[2], os.Args[3]

	var zb bytes.Buffer
	zw := zip.NewWriter(&zb)
	err := filepath.WalkDir(src, func(p string, d fs.DirEntry, err error) error {
		if err != nil || d.IsDir() {
			return err
		}
		rel, _ := filepath.Rel(src, p)
		w, err := zw.Create(filepath.ToSlash(rel))
		if err != nil {
			return err
		}
		b, err := os.ReadFile(p)
		if err != nil {
			return err
		}
		_, err = w.Write(b)
		return err
	})
	check(err)
	check(zw.Close())

	key := make([]byte, 32)
	nonce := make([]byte, 12)
	_, err = rand.Read(key)
	check(err)
	_, err = rand.Read(nonce)
	check(err)
	block, err := aes.NewCipher(key)
	check(err)
	gcm, err := cipher.NewGCM(block)
	check(err)
	check(os.WriteFile(outBin, append(nonce, gcm.Seal(nil, nonce, zb.Bytes(), nil)...), 0o644))

	// The key is stored split into two masked halves so it isn't a single recognisable run of bytes.
	mask := make([]byte, 32)
	_, err = rand.Read(mask)
	check(err)
	var masked []string
	var ms []string
	for i := range key {
		masked = append(masked, fmt.Sprintf("0x%02x", key[i]^mask[i]))
		ms = append(ms, fmt.Sprintf("0x%02x", mask[i]))
	}
	code := "// Code generated by pack; DO NOT EDIT.\n\npackage main\n\nvar kA = []byte{" + strings.Join(masked, ", ") +
		"}\nvar kB = []byte{" + strings.Join(ms, ", ") + "}\n"
	check(os.WriteFile(outKey, []byte(code), 0o644))
}

func check(err error) {
	if err != nil {
		fmt.Fprintln(os.Stderr, err)
		os.Exit(1)
	}
}
